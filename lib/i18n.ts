export function isLocale(value: string | null | undefined): value is Locale {
  return value === 'en'
}

export function resolveLocale(value: string | null | undefined): Locale {
  return isLocale(value) ? value : 'en'
}

export function getMessages(locale: Locale) {
  return messages[locale]
}

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  const template = messages[locale][key] ?? messages.en[key]

  if (!vars) {
    return template
  }

  return template.replace(/\{(\w+)\}/g, (_: string, token: string) =>
    String(vars[token] ?? `{${token}}`)
  )
}

export function translateStatus(locale: Locale, value: string) {
  return statusLabels[locale][value as keyof (typeof statusLabels)['en']] ?? value
}

export function translateType(locale: Locale, value: string) {
  return typeLabels[locale][value as keyof (typeof typeLabels)['en']] ?? value
}

export function formatDateForLocale(locale: Locale, value: string | null) {
  void locale
  if (!value) {
    return t(locale, 'common.unknown')
  }

  return new Intl.DateTimeFormat('en-US', {
    dateStyle: 'medium',
  }).format(new Date(value))
}

