import { test, expect } from '@playwright/test'
import { authenticate, fixture } from './helpers'

test.beforeEach(() => { fixture() })

test('desktop keyboard skip link and utility navigation have visible focus and a return path', async ({ page }) => {
  await authenticate(page.context())
  await page.goto('/')
  await page.keyboard.press('Tab')
  const skip = page.getByRole('link', { name: 'Skip to content', exact: true })
  await expect(skip).toBeFocused()
  await expect(skip).toBeInViewport()
  await page.keyboard.press('Enter')
  await expect(page.locator('#main-content')).toBeFocused()
  const utility = page.getByRole('button', { name: 'Open utility menu', exact: true })
  await utility.focus()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('link', { name: 'Import', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(utility).toBeFocused()
  await expect(utility).toHaveAttribute('aria-expanded', 'false')
})

test('mobile menu focus, single capture dialog and short-screen scrolling preserve reachable controls', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 600 })
  await authenticate(page.context())
  await page.goto('/')
  const trigger = page.getByRole('button', { name: 'Open menu', exact: true })
  await trigger.click()
  const menu = page.getByRole('dialog', { name: 'Navigation', exact: true })
  const close = menu.getByRole('button', { name: 'Close menu', exact: true })
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(menu.getByRole('button', { name: 'Logout', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden')
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await trigger.click()
  await menu.getByRole('button', { name: '+ Add New', exact: true }).click()
  const capture = page.getByRole('dialog')
  await expect(capture).toHaveCount(1)
  await expect(capture.getByRole('searchbox', { name: 'Title', exact: true })).toBeInViewport()
  const titleBounds = await capture.getByRole('searchbox', { name: 'Title', exact: true }).boundingBox()
  const saveBounds = await capture.getByRole('button', { name: 'Save Item', exact: true }).boundingBox()
  expect(titleBounds!.y + titleBounds!.height).toBeLessThan(saveBounds!.y)
  await expect(capture.locator('details')).not.toHaveAttribute('open')
  await capture.locator('summary').focus()
  await page.keyboard.press('Enter')
  await expect(capture.getByRole('textbox', { name: 'Quick Import Link', exact: true })).toBeVisible()
  await capture.locator('summary').focus()
  await page.keyboard.press('Enter')
  await expect(capture.locator('details')).not.toHaveAttribute('open')
  const bounds = await capture.boundingBox()
  expect(bounds!.y).toBeGreaterThanOrEqual(0)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(600)
  const save = capture.getByRole('button', { name: 'Save Item', exact: true })
  await save.scrollIntoViewIfNeeded()
  await expect(save).toBeInViewport()
  await expect(capture.getByRole('button', { name: 'Close modal', exact: true })).toBeInViewport()
  const field = capture.getByRole('searchbox', { name: 'Title', exact: true })
  expect(await field.evaluate(element => parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(16)
  await capture.getByRole('button', { name: 'Close modal', exact: true }).click()
  await expect(capture).toHaveCount(0)
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
  await expect(trigger).toBeFocused()
})

test('all key screens remain usable at 320px and detail titles precede the compact snapshot', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  const client = await authenticate(page.context())
  for (const path of ['/', '/discover', '/lists', '/import', '/backup', '/summary', '/stats', '/settings']) {
    await page.goto(path, { waitUntil: 'domcontentloaded' })
    await expect(page.locator('main h1')).toBeVisible()
    await expect(page.locator('main h1')).not.toHaveText('The vault hit an unexpected error')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  }
  await expect(page.getByText('Settings schema required', { exact: true })).toHaveCount(0)
  await expect(page.getByText(/Developer note:/)).toHaveCount(0)
  await page.goto('/import')
  await page.getByRole('navigation', { name: 'Import formats' }).getByRole('link', { name: 'CSV', exact: true }).click()
  await expect(page).toHaveURL(/#csv-import$/)
  await expect(page.getByRole('heading', { name: 'CSV Import', exact: true })).toBeInViewport()
  const row = await client.from('items').select('id,title').eq('user_id', fixture().a).limit(1).single()
  expect(row.error).toBeNull()
  await page.goto(`/items/${row.data!.id}`)
  const heading = page.getByRole('heading', { level: 1 })
  await expect(heading).toHaveText(row.data!.title)
  expect((await heading.boundingBox())!.y).toBeLessThan(400)
  expect((await page.getByRole('link', { name: 'Edit', exact: true }).boundingBox())!.height).toBeGreaterThanOrEqual(44)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

test('catalog clear is keyboard accessible and preserves media-type selection', async ({ page }) => {
  await authenticate(page.context())
  await page.route('**/api/catalog-search', route => route.fulfill({ json: { data: [], page: 1, hasMore: false, provider: 'TMDB' } }))
  await page.goto('/discover?type=movie&q=synthetic')
  const clear = page.getByRole('button', { name: 'Clear catalog search', exact: true })
  await clear.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('textbox', { name: 'Search titles', exact: true })).toBeFocused()
  await expect(page).toHaveURL(url => url.searchParams.get('type') === 'movie' && !url.searchParams.has('q'))
})

test('private sharing controls stay honest and denied clipboard access offers a manual copy link', async ({ page, context }) => {
  const client = await authenticate(context)
  expect((await client.from('profiles').update({ is_public: false }).eq('id', fixture().a)).error).toBeNull()
  await page.goto('/stats')
  await expect(page.getByRole('link', { name: 'Manage profile sharing', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Copy public profile link', exact: true })).toHaveCount(0)
  await context.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('Synthetic clipboard denial') } } }))
  expect((await client.from('profiles').update({ is_public: true }).eq('id', fixture().a)).error).toBeNull()
  try {
    await page.reload()
    await page.getByRole('button', { name: 'Copy public profile link', exact: true }).click()
    const input = page.getByRole('textbox', { name: 'Sharing link', exact: true })
    await expect(input).toBeVisible()
    await input.focus()
    expect(await input.evaluate(element => {
      const field = element as HTMLInputElement
      return field.selectionEnd! - field.selectionStart! === field.value.length
    })).toBe(true)
  } finally { await client.from('profiles').update({ is_public: false }).eq('id', fixture().a) }
})
